def fmt(t: str) -> str:
    t = html.escape(t)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    return t.replace(" • ", "<br>• ")


def main() -> None:
    paras = paragraphs()
    rows, warn = [], 0
    for i, (kind, en) in enumerate(paras):
        key, ko = KO[i] if i < len(KO) else ("", "")
        ok = en.lstrip("*").startswith(key.lstrip("*")) and key
        if not ok:
            warn += 1
        flag = "" if ok else '<span class="warn">번역 확인 필요 (영어 문단이 바뀜)</span>'
        if kind == "section":
            rows.append(f"<h2>{html.escape(ko or en)} <small style='color:var(--dim)'>· {html.escape(en)}</small>{flag}</h2>")
        else:
            rows.append(f'<div class="row"><div class="en">{fmt(en)}</div><div class="ko">{flag}{fmt(ko)}</div></div>')
    if len(KO) != len(paras):
        warn += 1
    page = (f"<!doctype html><html lang='ko'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>논문 한국어 대조</title><style>{CSS}</style></head><body><main><h1>논문 초안 한국어 대조판</h1>"
            f"<div class='note'>공부·확인용. 제출은 영어판(paper/main.tex). 영어 문단은 main.tex에서 바로 뽑아 숫자를 채웠다. "
            f"표·그림은 빠져 있으니 main.pdf와 같이 본다. [ref]는 인용 자리.</div>{''.join(rows)}</main></body></html>")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(page, encoding="utf-8")
    print(f"→ {OUT}  문단 {len(paras)}개, 번역 {len(KO)}개, 확인 필요 {warn}")


if __name__ == "__main__":
    main()
